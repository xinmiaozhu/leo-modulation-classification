def _torch_parameter_count(path: Path) -> int:
    checkpoint = torch.load(path, map_location="cpu", weights_only=False)
    state = checkpoint.get("model_state_dict", checkpoint)
    buffer_suffixes = ("running_mean", "running_var", "num_batches_tracked")
    return int(
        sum(
            value.numel()
            for key, value in state.items()
            if torch.is_tensor(value) and not key.endswith(buffer_suffixes)
        )
    )


def _summarize(args: argparse.Namespace) -> None:
    if args.dry_run:
        print(f"Dry-run: summary would be saved to {args.summary_output}")
        return
    rows: list[dict[str, object]] = []
    for key in args.methods:
        method = METHODS[key]
        eval_csv = _eval_csv(args, key)
        if not eval_csv.exists():
            raise FileNotFoundError(f"Missing evaluation result: {eval_csv}")
        df = pd.read_csv(eval_csv, usecols=["correct"])
        checkpoint_path = _checkpoint_dir(args, key) / "best.pt" if method.model_name else None
        parameters = _torch_parameter_count(checkpoint_path) if checkpoint_path is not None else np.nan
        support_vectors = np.nan
        checkpoint = str(checkpoint_path) if checkpoint_path is not None else "N/A"
        rows.append(
            {
                "method_id": method.method_id,
                "method": key,
                "display_label": method.display_label,
                "description": method.description,
                "accuracy": float(df["correct"].mean()),
                "num_samples": int(len(df)),
                "parameter_count": parameters,
                "support_vector_count": support_vectors,
                "checkpoint": checkpoint,
                "eval_csv": str(eval_csv),
                "reference": method.reference,
            }
        )

    if not args.no_proposed:
        proposed_csv = Path(args.proposed_eval_csv)
        if not proposed_csv.exists():
            raise FileNotFoundError(f"Missing proposed-model evaluation: {proposed_csv}")
        df = pd.read_csv(proposed_csv, usecols=["correct"])
        rows.append(
            {
                "method_id": "Proposed",
                "method": "proposed",
                "display_label": "Proposed I/Q+EVM",
                "description": "Compact pilot-compensated I/Q+EVM model",
                "accuracy": float(df["correct"].mean()),
                "num_samples": int(len(df)),
                "parameter_count": _torch_parameter_count(Path(args.proposed_checkpoint)),
                "support_vector_count": np.nan,
                "checkpoint": args.proposed_checkpoint,
                "eval_csv": str(proposed_csv),
                "reference": "This work",
            }
        )

    summary = pd.DataFrame(rows)
    print("\nPaper baseline comparison")
    print(summary[["method_id", "display_label", "accuracy", "parameter_count"]].to_string(index=False))
    output = Path(args.summary_output)
    output.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(output, index=False)
    save_json(
        {
            "summary_csv": str(output),
            "raw_data": args.raw_data,
            "feature_data": args.feature_data,
            "paper_feature_data": args.paper_feature_data,
            "splits": args.splits,
            "eval_split": args.eval_split,
            "input_policy": (
                "E0 uses the minimum raw all-candidate EVM score after pilot compensation; "
                "C1-C4 use pilot-compensated IQ; C5 uses nine symbol cumulants plus "
                "pilot-EVM Es/N0 estimate."
            ),
            "adaptation_policy": (
                "Long frames are divided into each paper's native window "
                "length and window logits are averaged. Output width is seven."
            ),
            "strict_same_input_experiment": False,
        },
        output.with_suffix(".json"),
    )
    print(f"Saved: {output}")


def _plot(args: argparse.Namespace) -> None:
    cmd = [
        sys.executable,
        _script("46_plot_paper_baseline_comparison.py"),
        "--summary",
        args.summary_output,
        "--output-dir",
        args.figure_root,
        "--table-output",
        str(Path(args.result_root) / "snr_curve.csv"),
        "--accuracy-output",
        "paper_baseline_coherent_accuracy_vs_snr.pdf",
        "--overall-output",
        "paper_baseline_coherent_overall_accuracy.pdf",
    ]
    _run(cmd, args.dry_run)


def main() -> None:
    args = parse_args()
    _validate_inputs(args)
    Path(args.checkpoint_root).mkdir(parents=True, exist_ok=True)
    Path(args.result_root).mkdir(parents=True, exist_ok=True)

    if "features" in args.stages:
        _precompute_paper_features(args)

    for key in args.methods:
        method = METHODS[key]
        print(f"\n=== {method.method_id}: {method.display_label} ===")
        if "train" in args.stages:
            _train_deep(args, method)
        if "eval" in args.stages:
            _evaluate_deep(args, method)

    if "eval" in args.stages:
        _evaluate_proposed(args)
    if "summary" in args.stages:
        _summarize(args)
    if "plots" in args.stages:
        if not Path(args.summary_output).exists() and not args.dry_run:
            raise FileNotFoundError("Run the summary stage before plots.")
        _plot(args)


if __name__ == "__main__":
    main()
