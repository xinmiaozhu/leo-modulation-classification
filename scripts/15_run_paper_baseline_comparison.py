def _script(name: str) -> str:
    return str(PROJECT_ROOT / "scripts" / name)


def _run(cmd: list[str], dry_run: bool) -> None:
    printable = " ".join(f'"{x}"' if " " in str(x) else str(x) for x in cmd)
    print(f"\n$ {printable}")
    if not dry_run:
        subprocess.run(cmd, check=True)


def _checkpoint_dir(args: argparse.Namespace, key: str) -> Path:
    return Path(args.checkpoint_root) / key


def _eval_csv(args: argparse.Namespace, key: str) -> Path:
    return Path(args.result_root) / f"{key}_{args.eval_split}.csv"


def _eval_summary(args: argparse.Namespace, key: str) -> Path:
    return Path(args.result_root) / f"{key}_{args.eval_split}.summary.json"


def _validate_inputs(args: argparse.Namespace) -> None:
    paths = {
        "raw_data": args.raw_data,
        "feature_data": args.feature_data,
        "splits": args.splits,
        "train_config": args.train_config,
    }
    if "features" in args.stages or "e0_nearest_evm" in args.methods:
        paths["symbol_feature_data"] = args.symbol_feature_data
    elif "c6_nasa_hoc_nn" in args.methods:
        paths["paper_feature_data"] = args.paper_feature_data
    for key in args.methods:
        cfg = METHODS[key].model_config
        if cfg is not None:
            paths[f"model_config[{key}]"] = cfg
    if not args.no_proposed and not Path(args.proposed_eval_csv).exists():
        paths["proposed_checkpoint"] = args.proposed_checkpoint
        paths["proposed_model_config"] = args.proposed_model_config
        paths["symbol_feature_data"] = args.symbol_feature_data
    missing = [f"{name}: {path}" for name, path in paths.items() if not Path(path).exists()]
    if missing:
        raise SystemExit("Missing required input(s):\n" + "\n".join(missing))


def _precompute_paper_features(args: argparse.Namespace) -> None:
    cmd = [
        sys.executable,
        _script("11_precompute_paper_baseline_features.py"),
        "--raw-data",
        args.raw_data,
        "--comp-feature-data",
        args.feature_data,
        "--symbol-feature-data",
        args.symbol_feature_data,
        "--output",
        args.paper_feature_data,
    ]
    if args.overwrite:
        cmd.append("--overwrite")
    _run(cmd, args.dry_run)


def _train_deep(args: argparse.Namespace, method: PaperMethod) -> None:
    if method.model_name is None:
        print(f"No training required: {method.display_label}")
        return
    out_dir = _checkpoint_dir(args, method.key)
    completed = out_dir / "train_result.json"
    if completed.exists() and (out_dir / "best.pt").exists() and not args.overwrite:
        print(f"Skip existing: {completed}")
        return
    feature_data = (
        args.paper_feature_data
        if method.key == "c6_nasa_hoc_nn"
        else args.feature_data
    )
    iq_source = "raw" if method.key == "c6_nasa_hoc_nn" else "comp"
    iq_normalize = "power" if method.key == "c4_cnn_lstm_dual" else "zscore"
    hoc_transform = "none" if method.key == "c6_nasa_hoc_nn" else "signed_log1p"
    cmd = [
        sys.executable,
        _script("13_train_model.py"),
        "--raw-data",
        args.raw_data,
        "--feature-data",
        feature_data,
        "--splits",
        args.splits,
        "--model",
        str(method.model_name),
        "--model-config",
        str(method.model_config),
        "--train-config",
        args.train_config,
        "--output-dir",
        str(out_dir),
        "--device",
        args.device,
        "--num-workers",
        "0",
        "--iq-source",
        iq_source,
        "--iq-normalize",
        iq_normalize,
        "--hoc-transform",
        hoc_transform,
    ]
    if method.key != "c6_nasa_hoc_nn":
        cmd.append("--cache-iq")
    if method.key != "c6_nasa_hoc_nn":
        cmd.extend(["--no-hoc-standardize"])
    last = out_dir / "last.pt"
    if last.exists() and not completed.exists() and not args.overwrite:
        cmd.extend(["--resume", str(last)])
    _run(cmd, args.dry_run)


def _evaluate_nearest_evm(
    args: argparse.Namespace,
    method: PaperMethod,
    output: Path,
    summary: Path,
) -> None:
    """Evaluate the protocol-matched, zero-training minimum-EVM reference.

    This is not labelled as a faithful reproduction of an external EVM-AMC
    implementation. It evaluates the direct decision rule available from this
    receiver's compensated all-candidate EVM scores.
    """

    with np.load(args.splits) as split_file:
        if args.eval_split not in split_file:
            raise KeyError(f"Split {args.eval_split!r} is missing from {args.splits}")
        indices = np.asarray(split_file[args.eval_split], dtype=np.int64)

    with h5py.File(args.symbol_feature_data, "r") as feature_file:
        required = {"all_candidate_evm", "label", "snr_db", "symbol_valid"}
        missing = sorted(required.difference(feature_file.keys()))
        if missing:
            raise KeyError(
                "Symbol feature data is missing required EVM-reference datasets: "
                f"{missing}"
            )
        scores = np.asarray(feature_file["all_candidate_evm"][indices], dtype=np.float64)
        labels = np.asarray(feature_file["label"][indices], dtype=np.int64)
        snr_db = np.asarray(feature_file["snr_db"][indices], dtype=np.float64)
        valid = np.asarray(feature_file["symbol_valid"][indices], dtype=bool)

    pred = np.argmin(np.where(np.isfinite(scores), scores, np.inf), axis=1).astype(np.int64)
    correct = valid & (pred == labels)
    frame = pd.DataFrame(
        {
            "index": indices,
            "label": labels,
            "pred": pred,
            "correct": correct.astype(np.int8),
            "snr_db": snr_db,
            "symbol_valid": valid,
        }
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(output, index=False)
    save_json(
        {
            "method": method.key,
            "display_label": method.display_label,
            "decision_rule": "argmin_m all_candidate_evm[m]",
            "score_type": "raw EVM without order or APSK penalties",
            "protocol_note": (
                "Protocol-matched zero-training reference; not a faithful reproduction "
                "of an external EVM-AMC implementation."
            ),
            "num_samples": int(len(frame)),
            "valid_fraction": float(np.mean(valid)) if len(valid) else float("nan"),
            "accuracy": float(np.mean(correct)) if len(correct) else float("nan"),
        },
        summary,
    )
    print(f"Saved EVM hard-decision evaluation: {output}")


def _evaluate_deep(args: argparse.Namespace, method: PaperMethod) -> None:
    output = _eval_csv(args, method.key)
    summary = _eval_summary(args, method.key)
    if output.exists() and summary.exists() and not args.overwrite:
        print(f"Skip existing: {output}")
        return
    if method.model_name is None:
        _evaluate_nearest_evm(args, method, output, summary)
        return
    feature_data = (
        args.paper_feature_data
        if method.key == "c6_nasa_hoc_nn"
        else args.feature_data
    )
    cmd = [
        sys.executable,
        _script("14_evaluate_model.py"),
        "--checkpoint",
        str(_checkpoint_dir(args, method.key) / "best.pt"),
        "--raw-data",
        args.raw_data,
        "--feature-data",
        feature_data,
        "--splits",
        args.splits,
        "--split",
        args.eval_split,
        "--model",
        str(method.model_name),
        "--model-config",
        str(method.model_config),
        "--output",
        str(output),
        "--summary-output",
        str(summary),
        "--batch-size",
        str(args.batch_size_eval),
        "--num-workers",
        "0",
        "--device",
        args.device,
        "--no-aux",
    ]
    if method.key != "c6_nasa_hoc_nn":
        cmd.append("--cache-iq")
    _run(cmd, args.dry_run)


